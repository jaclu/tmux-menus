cache_write_plugin_params() {
    #
    #  Writes all config params to file
    #  if it differed with previous params, clear cache
    #
    # log_it "cache_write_plugin_params()"
    get_env

    ${cfg_use_cache:-false} || error_msg "cache_write_plugin_params() - called when not using cache"

    # cloud node .22 jacmac .25 jacpad 2.5 jacdoid 1
    check_speed_cutoff 0.5
    examine_code_base

    _f_params_tmp=$(mktemp -t tmux-menus-plugins-params.XXXXXX) || {
        error_msg "cache_write_plugin_params() - Failed to create tmp config file"
    }

    params_basic
    [ -n "$alt_menu_handler" ] || {
        params_no_alt_handler
        params_34
        params_38
    }
    params_not_config_1
    params_tmux_plugins_manager_path
    params_tmux_vers
    params_not_config_2
    params_alt_handler

    if [ -f "$f_cache_params" ]; then
        if ! diff -q "$_f_params_tmp" "$f_cache_params" >/dev/null 2>&1; then
            # diff reports success if files don't differ, hence the !
            # If any params have changed, invalidate cache

            cache_clear "=======   Environment changed:  $(
                diff "$_f_params_tmp" "$f_cache_params"
            )"
            mv "$_f_params_tmp" "$f_cache_params" || error_msg "Failed to write to tmpfile: $f_cache_params"
            _f_params_tmp=""
            [ -n "$cfg_log_file" ] && [ -f "$cfg_log_file" ] && {
                # not strictly needed, the cache files will be created
                # when needed, doing it here is mostly to ensure they are always
                # available for debug checks
                cache_save_options_defined_in_tmux
            }
        else
            # log_it " config unchanged - param cache not cleared"
            safe_remove "$_f_params_tmp" "cache_write_plugin_params() - remove tmpfile"
            _f_params_tmp=""
        fi
    else
        mv "$_f_params_tmp" "$f_cache_params" || error_msg "Failed to replace: $f_cache_params"
        _f_params_tmp=""
    fi
}

verify_tmux_vers_unchanged() {
    # Compare current tmux vers with param cache, dropping param cache fully
    # if they differ

    actual_current_tmux_vers="$current_tmux_vers"
    #

    # Source the param cache in a subshell, and only keep current_tmux_vers,
    # in order to make sure no other variables gets leaked into the env
    previous_current_tmux_vers=$(
        # source the cached params in a subshell, in order to only extract
        # current_tmux_vers for comparison

        # shellcheck disable=SC2030 # subshell override if fine here
        cfg_log_file=""

        current_tmux_vers="unknown"

        source_cached_params
        echo "$current_tmux_vers"
    )
    current_tmux_vers="$actual_current_tmux_vers"
    [ "$actual_current_tmux_vers" != "$previous_current_tmux_vers" ] && {
        # If tmux version has changed, the entire cache should be dropped
        _s2="tmux version change: $previous_current_tmux_vers -> $actual_current_tmux_vers"
        log_it "$_s2 - dropping entire cache"

        safe_remove "$d_cache/*" "verify_tmux_vers_unchanged()"

        # Clear in memory cache of good/bad tmux versions, that might have been
        # read from invalid cache
        cached_ok_tmux_versions=""
        cached_bad_tmux_versions=""
        return 1
    }
    return 0
}

